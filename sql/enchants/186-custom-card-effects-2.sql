-- What the three Arcane custom Mystic Enchant cards do (the cards: file 184, client-patch/custom_cards.py). All three are
-- Ascension talents whose spell data only names the effect; the scripts are in patches/55-talent-fixes.ps1 ("Custom
-- Mystic Enchant cards, batch 2"), so this needs the build with them. Sources: our spell data (Spell.dbc) and each
-- tooltip. Not tested in game: unverified until tested.
--
-- Arcane Crusade 277880 (Legendary). Its own two effects (a placeholder and a stray paladin trigger) become Arcane
-- Missiles' faster channel: 44% shorter channel and 44% shorter time between missiles (the tooltip's "80% faster",
-- read as speed: 1 / 1.8), so the same missiles land sooner. The scripts add: Arcane Missiles 150% more damage (30%
-- against players) and a 12 sec cooldown; Arcane Barrage 100% more damage (30% against players) and a 35% chance per
-- cast to grant Missile Barrage if you know the talent; Arcane Explosion a second explosion and a Missile Barrage charge
-- if you know the talent.
-- Assumptions: "Sanctity of Battle now also affects Arcane Mage spells" is not required (the card works without the
-- paladin talent); the tooltip's Seal of Arcane Wrath line and the Synchronize note are left out.
--
-- Arcanesworn 277850 (Epic). Crusader Strike and Divine Storm use up Missile Barrage to strike with Arcanesworn
-- (277851, 75% off-hand weapon damage as Arcane to up to 3 enemies) and take 10 sec off Avenging Wrath and 4 sec off
-- Divine Illumination. Its own proc effects had no proc rule, so nothing happened; the script does it, once per cast.
--
-- Arcane Divinity 275462 (Epic). While Divine Illumination is up, Arcane Blast, Arcane Missiles and Arcane Barrage deal
-- Divine damage: the hit becomes Holy and Arcane, and takes the Holy damage bonus when that is higher. Its spell is only
-- a placeholder, so the roll filter (SkipDudSpells) would leave the card out: wcme_enchant_override keeps it in.
-- Known limit: the hit's crit chance is the Holy one (the core uses the first school of a mixed hit for a player's spell
-- crit), so an Arcane-only crit bonus doesn't count while Divine Illumination is up.
--
-- Safe to run again: 000-reset removes everything here first.
